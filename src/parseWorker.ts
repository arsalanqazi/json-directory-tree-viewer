/**
 * Web Worker for parsing large JSON tree files off the main thread.
 * Receives raw JSON string, processes it into a TreeSource, and posts back the result.
 *
 * Usage from main thread:
 *   const worker = new Worker(new URL('./parseWorker.ts', import.meta.url), { type: 'module' });
 *   worker.postMessage({ id, name, rawJson });
 *   worker.onmessage = (e) => { const treeSource = e.data; };
 */

// --- Duplicated processing logic (Workers can't import from the main bundle) ---

type NodeType = 'directory' | 'file' | 'link' | 'socket' | 'report' | 'fifo' | 'device';

interface TreeItem {
  type: NodeType;
  name: string;
  size?: number;
  mode?: string;
  prot?: string;
  uid?: number;
  user?: string;
  gid?: number;
  group?: string;
  time?: string;
  contents?: TreeItem[];
  id: string;
  parentPath?: string;
  depth: number;
  extension: string;
  treeSourceId: string;
}

interface TreeSource {
  id: string;
  name: string;
  importedAt: string;
  rawJson?: string;
  rootNodes: TreeItem[];
  directoriesCount: number;
  filesCount: number;
  totalSize: number;
}

/**
 * Iteratively processes raw JSON nodes into TreeItem objects.
 * Uses an explicit stack instead of recursion to avoid stack overflow on deeply nested trees.
 */
function processRawNodes(rawNodes: any[]): any[] {
  const rootResults: any[] = [];

  // Stack items: { raw node, parentContentsArray }
  type StackItem = {
    raw: any;
    target: any[];
  };

  const stack: StackItem[] = [];

  // Push root nodes in reverse order so they are processed in original order
  for (let i = rawNodes.length - 1; i >= 0; i--) {
    stack.push({ raw: rawNodes[i], target: rootResults });
  }

  while (stack.length > 0) {
    const { raw, target } = stack.pop()!;

    // Handle standalone error objects generated by 'tree' when directory permissions fail
    if (raw.error && !raw.name) {
      target.push({
        type: 'file',
        name: `⚠️ Error: ${raw.error}`,
        size: 0,
        depth: 0,
        extension: '',
        treeSourceId: ''
      });
      continue;
    }

    const name = (raw.name || 'unnamed').replace(/^\.\//, '');
    const processed: any = {
      type: raw.type || 'file',
      name,
    };

    if (typeof raw.size === 'number') processed.size = raw.size;
    if (raw.mode) processed.mode = raw.mode;
    if (raw.prot) processed.prot = raw.prot;
    if (raw.uid !== undefined) processed.uid = raw.uid;
    if (raw.user) processed.user = raw.user;
    if (raw.gid !== undefined) processed.gid = raw.gid;
    if (raw.group) processed.group = raw.group;
    if (raw.time) processed.time = raw.time;

    if (raw.contents && Array.isArray(raw.contents)) {
      processed.contents = [];
      // Push children in reverse order for correct processing order
      for (let i = raw.contents.length - 1; i >= 0; i--) {
        stack.push({
          raw: raw.contents[i],
          target: processed.contents,
        });
      }
    }

    target.push(processed);
  }

  return rootResults;
}

/**
 * Iteratively counts files, directories, and total size.
 */
function countNodesIterative(rootNodes: TreeItem[]): { files: number; dirs: number; size: number } {
  let files = 0;
  let dirs = 0;
  let size = 0;

  const stack = [...rootNodes];

  while (stack.length > 0) {
    const node = stack.pop()!;
    size += node.size || 0;

    if (node.type === 'directory') {
      dirs++;
      if (node.contents) {
        for (let i = 0; i < node.contents.length; i++) {
          stack.push(node.contents[i]);
        }
      }
    } else {
      files++;
    }
  }

  return { files, dirs, size };
}

