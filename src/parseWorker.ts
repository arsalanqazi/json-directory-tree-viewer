import clarinet from 'clarinet';

/**
 * Robustly inserts commas between adjacent JSON objects/arrays (e.g. `}{` or `][`)
 * that are missing a comma, which frequently happens in malformed outputs like from the `tree` command.
 */
function fixMissingCommas(chunk: string, state: { lastChar: string }): string {
  let text = chunk;
  const needRestore = state.lastChar === '}' || state.lastChar === ']';
  if (needRestore) {
    text = state.lastChar + text;
  }
  
  // Regex to match } or ] followed by optional whitespace followed by { or [
  // and insert a comma between them if not present.
  text = text.replace(/([\}\]])(\s*)([\{\[])/g, '$1,$2$3');
  
  if (needRestore) {
    if (text.charAt(1) === ',') {
      text = ',' + text.slice(2);
    } else {
      text = text.slice(1);
    }
  }
  
  const trimmed = text.trimEnd();
  if (trimmed.length > 0) {
    state.lastChar = trimmed.charAt(trimmed.length - 1);
  }
  
  return text;
}

function parseJsonStream(file: File | Blob): Promise<any> {
  return new Promise(async (resolve, reject) => {
    const parser = clarinet.parser();
    
    let rootValue: any = undefined;
    const stack: any[] = [];
    let currentContainer: any = null;
    let currentKey: string | undefined = undefined;

    parser.onvalue = (v: any) => {
      if (currentContainer === null) {
        rootValue = v;
      } else if (Array.isArray(currentContainer)) {
        currentContainer.push(v);
      } else {
        currentContainer[currentKey as string] = v;
      }
    };

    parser.onopenobject = (key?: string) => {
      const obj: any = {};
      if (currentContainer === null) {
        rootValue = obj;
      } else if (Array.isArray(currentContainer)) {
        currentContainer.push(obj);
      } else {
        currentContainer[currentKey as string] = obj;
      }
      stack.push(currentContainer);
      currentContainer = obj;
      currentKey = key;
    };

    parser.onkey = (key: string) => {
      currentKey = key;
    };

    parser.oncloseobject = () => {
      currentContainer = stack.pop();
    };

    parser.onopenarray = () => {
      const arr: any[] = [];
      if (currentContainer === null) {
        rootValue = arr;
      } else if (Array.isArray(currentContainer)) {
        currentContainer.push(arr);
      } else {
        currentContainer[currentKey as string] = arr;
      }
      stack.push(currentContainer);
      currentContainer = arr;
    };

    parser.onclosearray = () => {
      currentContainer = stack.pop();
    };

    parser.onerror = (err: any) => {
      reject(err);
    };

    parser.onend = () => {
      resolve(rootValue);
    };

    try {
      const stream = file.stream();
      const reader = stream.getReader();
      const decoder = new TextDecoder('utf-8');
      const streamState = { lastChar: '' };

      while (true) {
        const { done, value } = await reader.read();
        if (done) break;
        let chunk = decoder.decode(value, { stream: true });
        
        // Fix any missing commas in this chunk (e.g. `}{"error":`)
        chunk = fixMissingCommas(chunk, streamState);
        
        parser.write(chunk);
      }
      // Ensure the decoder flushes properly if there are trailing bytes
      let finalChunk = decoder.decode(new Uint8Array(0));
      if (finalChunk) {
        finalChunk = fixMissingCommas(finalChunk, streamState);
        parser.write(finalChunk);
      }
      
      parser.close();
    } catch (err) {
      reject(err);
    }
  });
}

self.onmessage = async function (e: MessageEvent<{ id: string; name: string; file: File | Blob }>) {
  const { id, name, file } = e.data;

  try {
    const parsed = await parseJsonStream(file);
    const dataArray = Array.isArray(parsed) ? parsed : [parsed];
    const dataNodes = dataArray.filter((node: any) => node.type !== 'report');

    const rootNodes = processRawNodes(dataNodes);
    const counts = countNodesIterative(rootNodes);

    const rootNodesJson = JSON.stringify(rootNodes);

    (self as any).postMessage({
      success: true,
      result: {
        id,
        name,
        importedAt: new Date().toLocaleString(),
        rootNodesJson,
        directoriesCount: counts.dirs,
        filesCount: counts.files,
        totalSize: counts.size,
      }
    });
  } catch (err: any) {
    (self as any).postMessage({ success: false, error: err.message || err.toString() });
  }
};
